#!/usr/bin/env python3
"""Build KORA's compact next-word model from Common Voice fub sentences (CC0)."""

from __future__ import annotations

import csv
import json
import sys
import unicodedata
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / ".models/common-voice/validated_sentences.tsv"
OUTPUT = ROOT / "src/fub-language-model.js"
MAX_UNIGRAMS = 1_200
MAX_CONTEXTS = 3_000
MAX_PREDICTIONS = 6
MIN_COUNT = 2


def tokenize(text: str) -> list[str]:
    normalized = unicodedata.normalize("NFKC", text).lower().replace("’", "'").replace("ʼ", "'")
    tokens: list[str] = []
    current: list[str] = []
    for character in normalized:
        if unicodedata.category(character).startswith("L") or (
            character in {"'", "-"} and current
        ):
            current.append(character)
        elif current:
            token = "".join(current).strip("'-")
            if token:
                tokens.append(token)
            current = []
    if current:
        token = "".join(current).strip("'-")
        if token:
            tokens.append(token)
    return tokens


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
    if not source.exists():
        raise SystemExit(f"Corpus absent: {source}")

    unigrams: Counter[str] = Counter()
    transitions: dict[str, Counter[str]] = defaultdict(Counter)
    sentence_count = 0
    token_count = 0

    with source.open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream, delimiter="\t"):
            tokens = tokenize(row.get("sentence", ""))
            if not tokens:
                continue
            sentence_count += 1
            token_count += len(tokens)
            unigrams.update(tokens)
            padded = ["<s>", "<s>", *tokens, "</s>"]
            for index in range(2, len(padded)):
                next_word = padded[index]
                transitions[f"1:{padded[index - 1]}"][next_word] += 1
                transitions[f"2:{padded[index - 2]} {padded[index - 1]}"][next_word] += 1

    compact_transitions: dict[str, list[list[str | int]]] = {}
    ranked_contexts = sorted(
        transitions.items(),
        key=lambda item: (-sum(item[1].values()), item[0]),
    )
    for context, counts in ranked_contexts:
        predictions = [
            [word, count]
            for word, count in counts.most_common(MAX_PREDICTIONS)
            if count >= MIN_COUNT
        ]
        if predictions:
            compact_transitions[context] = predictions
        if len(compact_transitions) >= MAX_CONTEXTS:
            break

    compact_unigrams = [
        [word, count]
        for word, count in unigrams.most_common(MAX_UNIGRAMS)
        if count >= MIN_COUNT
    ]
    metadata = {
        "language": "fub",
        "corpus": "Mozilla Common Voice 27.0 — Adamawa Fulfulde",
        "license": "CC0",
        "sentences": sentence_count,
        "tokens": token_count,
        "contexts": len(compact_transitions),
        "vocabulary": len(compact_unigrams),
        "kind": "interpolated unigram/bigram/trigram next-word model",
    }

    content = (
        "// Generated by scripts/build_fub_language_model.py from Common Voice fub CC0.\n"
        f"export const FUB_MODEL_META = Object.freeze({json.dumps(metadata, ensure_ascii=False, separators=(',', ':'))});\n"
        f"export const FUB_UNIGRAMS = Object.freeze({json.dumps(compact_unigrams, ensure_ascii=False, separators=(',', ':'))});\n"
        f"export const FUB_TRANSITIONS = Object.freeze({json.dumps(compact_transitions, ensure_ascii=False, separators=(',', ':'))});\n"
    )
    OUTPUT.write_text(content, encoding="utf-8")
    print(
        f"Generated {OUTPUT.relative_to(ROOT)}: "
        f"{sentence_count} sentences, {token_count} tokens, "
        f"{len(compact_transitions)} contexts, {OUTPUT.stat().st_size / 1024:.1f} KiB"
    )


if __name__ == "__main__":
    main()
