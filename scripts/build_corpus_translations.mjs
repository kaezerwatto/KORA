import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = path.join(root, "data/corpora/financial-terminology-candidates.json");
const inventoryInput = path.join(root, "data/corpora/index.json");
const output = path.join(root, "src/corpus-translations.js");
const allowedStatuses = new Set([
  "attested",
  "reviewed-existing",
  "compositional-candidate",
  "local-loan-candidate",
  "preserved-code"
]);

function normalize(value) {
  return String(value ?? "")
    .normalize("NFKC")
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, " ")
    .trim()
    .toLocaleLowerCase("fr");
}

function add(map, source, target, label) {
  const key = normalize(source);
  const value = String(target ?? "").normalize("NFC").trim();
  if (!key || !value) throw new Error(`Entrée ${label} incomplète`);
  if (map.has(key) && map.get(key) !== value) {
    throw new Error(`Conflit ${label} pour « ${source} »`);
  }
  map.set(key, value);
}

const document = JSON.parse(await readFile(input, "utf8"));
const inventory = JSON.parse(await readFile(inventoryInput, "utf8"));
if (!Array.isArray(document.entries)) {
  throw new Error("financial-terminology-candidates.json doit contenir entries[]");
}
const expectedFrench = new Set(
  inventory.sources.flatMap((source) => source.termLabels.map(normalize))
);
const actualFrench = new Set(document.entries.map((entry) => normalize(entry.fr)));
const missing = [...expectedFrench].filter((key) => !actualFrench.has(key));
const extra = [...actualFrench].filter((key) => !expectedFrench.has(key));
if (missing.length || extra.length || document.entries.length !== actualFrench.size) {
  throw new Error(
    `Couverture terminologique invalide: ${missing.length} manquantes, ` +
      `${extra.length} hors inventaire, ` +
      `${document.entries.length - actualFrench.size} doublons. ` +
      `Manquantes: ${missing.slice(0, 12).join(", ")}`
  );
}

const fr = new Map();
const en = new Map();
const preservedTerms = new Set();
const statuses = {};
for (const [index, entry] of document.entries.entries()) {
  const label = `#${index + 1}`;
  if (!allowedStatuses.has(entry.status)) {
    throw new Error(`${label}: statut inconnu « ${entry.status} »`);
  }
  if (!Array.isArray(entry.sources)) {
    throw new Error(`${label}: sources[] absent`);
  }
  if (
    ["attested", "reviewed-existing"].includes(entry.status) &&
    entry.sources.length === 0
  ) {
    throw new Error(`${label}: statut ${entry.status} sans source`);
  }
  if (!Array.isArray(entry.corpus) || entry.corpus.length === 0) {
    throw new Error(`${label}: corpus absent`);
  }
  if (entry.status === "preserved-code") {
    preservedTerms.add(String(entry.fr).normalize("NFC").trim());
    preservedTerms.add(String(entry.en).normalize("NFC").trim());
  } else {
    add(fr, entry.fr, entry.fub, `${label} FR`);
    add(en, entry.en, entry.fub, `${label} EN`);
  }
  statuses[entry.status] = (statuses[entry.status] ?? 0) + 1;
}

const metadata = {
  language: "fub",
  entries: document.entries.length,
  frenchKeys: fr.size,
  englishKeys: en.size,
  preservedTerms: preservedTerms.size,
  statuses,
  policy:
    "Corpus source labels are inventories, not parallel fub evidence; candidate status remains explicit."
};

const serialize = (map) =>
  JSON.stringify(Object.fromEntries([...map].sort(([a], [b]) => a.localeCompare(b))), null, 2);

const source = `// Generated by scripts/build_corpus_translations.mjs. Do not edit manually.
export const CORPUS_TRANSLATION_META = Object.freeze(${JSON.stringify(metadata, null, 2)});

export const CORPUS_FR_TO_FUB = Object.freeze(${serialize(fr)});

export const CORPUS_EN_TO_FUB = Object.freeze(${serialize(en)});

export const CORPUS_PRESERVED_TERMS = new Set(${JSON.stringify(
  [...preservedTerms].sort((a, b) => a.localeCompare(b)),
  null,
  2
)});
`;

await writeFile(output, source, "utf8");
console.log(
  `Generated ${path.relative(root, output)}: ${document.entries.length} entries, ` +
    `${fr.size} FR keys, ${en.size} EN keys`
);
